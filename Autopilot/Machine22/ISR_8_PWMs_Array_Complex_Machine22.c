// Include the ATmega_Slow_PWM library
#include "ATmega_Slow_PWM.h"

// Define the pins where PWM signals will be output (16 channels)
#define PWM_PIN_1   3   // PWM signal for Channel 1
#define PWM_PIN_2   4   // PWM signal for Channel 2
#define PWM_PIN_3   5   // PWM signal for Channel 3
#define PWM_PIN_4   6   // PWM signal for Channel 4
#define PWM_PIN_5   7   // PWM signal for Channel 5
#define PWM_PIN_6   8   // PWM signal for Channel 6
#define PWM_PIN_7   9   // PWM signal for Channel 7
#define PWM_PIN_8   10  // PWM signal for Channel 8
#define PWM_PIN_9   11  // PWM signal for Channel 9
#define PWM_PIN_10  12  // PWM signal for Channel 10
#define PWM_PIN_11  13  // PWM signal for Channel 11
#define PWM_PIN_12  14  // PWM signal for Channel 12
#define PWM_PIN_13  15  // PWM signal for Channel 13
#define PWM_PIN_14  16  // PWM signal for Channel 14
#define PWM_PIN_15  17  // PWM signal for Channel 15
#define PWM_PIN_16  18  // PWM signal for Channel 16

// Create PWM objects for each of the 16 channels
ATmega_Slow_PWM ISR_PWM1, ISR_PWM2, ISR_PWM3, ISR_PWM4, ISR_PWM5, ISR_PWM6, ISR_PWM7, ISR_PWM8;
ATmega_Slow_PWM ISR_PWM9, ISR_PWM10, ISR_PWM11, ISR_PWM12, ISR_PWM13, ISR_PWM14, ISR_PWM15, ISR_PWM16;

void setup() {
  // Initialize the Serial Monitor for debugging
  Serial.begin(115200);
  while (!Serial);

  Serial.println("Starting 16 ISR-Based PWM Channels");

  // Initialize PWM channels with their respective pins, frequencies, and duty cycles
  ISR_PWM1.setPWM(PWM_PIN_1, 1000, 50);    // Channel 1: 1kHz, 50% duty cycle
  ISR_PWM2.setPWM(PWM_PIN_2, 500, 25);     // Channel 2: 500Hz, 25% duty cycle
  ISR_PWM3.setPWM(PWM_PIN_3, 250, 75);     // Channel 3: 250Hz, 75% duty cycle
  ISR_PWM4.setPWM(PWM_PIN_4, 2000, 10);    // Channel 4: 2kHz, 10% duty cycle
  ISR_PWM5.setPWM(PWM_PIN_5, 1500, 60);    // Channel 5: 1.5kHz, 60% duty cycle
  ISR_PWM6.setPWM(PWM_PIN_6, 3000, 90);    // Channel 6: 3kHz, 90% duty cycle
  ISR_PWM7.setPWM(PWM_PIN_7, 4000, 50);    // Channel 7: 4kHz, 50% duty cycle
  ISR_PWM8.setPWM(PWM_PIN_8, 6000, 40);    // Channel 8: 6kHz, 40% duty cycle
  ISR_PWM9.setPWM(PWM_PIN_9, 5000, 70);    // Channel 9: 5kHz, 70% duty cycle
  ISR_PWM10.setPWM(PWM_PIN_10, 8000, 20);  // Channel 10: 8kHz, 20% duty cycle
  ISR_PWM11.setPWM(PWM_PIN_11, 9000, 30);  // Channel 11: 9kHz, 30% duty cycle
  ISR_PWM12.setPWM(PWM_PIN_12, 10000, 60); // Channel 12: 10kHz, 60% duty cycle
  ISR_PWM13.setPWM(PWM_PIN_13, 11000, 80); // Channel 13: 11kHz, 80% duty cycle
  ISR_PWM14.setPWM(PWM_PIN_14, 12000, 90); // Channel 14: 12kHz, 90% duty cycle
  ISR_PWM15.setPWM(PWM_PIN_15, 13000, 35); // Channel 15: 13kHz, 35% duty cycle
  ISR_PWM16.setPWM(PWM_PIN_16, 14000, 45); // Channel 16: 14kHz, 45% duty cycle

  // You can change these frequencies and duty cycles as per your application requirements
}

void loop() {
  // The PWM signals are generated by the ISR, so nothing is needed in the loop.
  // The ISR handles the timing independently of the loop, ensuring non-blocking execution.

  // You can adjust the frequencies and duty cycles dynamically if needed
  // Example: Update duty cycle of Channel 1 every 10 seconds
  static unsigned long lastTime = 0;
  if (millis() - lastTime > 10000) {
    int newDutyCycle = random(10, 90); // Random duty cycle between 10% and 90%
    ISR_PWM1.setPWM(PWM_PIN_1, 1000, newDutyCycle);
    Serial.print("Updated PWM1 Duty Cycle to: ");
    Serial.print(newDutyCycle);
    Serial.println("%");
    lastTime = millis();
  }

  delay(100);  // Short delay to prevent flooding the Serial Monitor
}
