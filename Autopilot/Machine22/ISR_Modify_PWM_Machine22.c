// Include the ATmega_Slow_PWM library
#include "ATmega_Slow_PWM.h"

// Define PWM pins for the first 8 channels (you can define all 16 if needed)
#define PWM_PIN_1  3   // Channel 1
#define PWM_PIN_2  4   // Channel 2
#define PWM_PIN_3  5   // Channel 3
#define PWM_PIN_4  6   // Channel 4
#define PWM_PIN_5  7   // Channel 5
#define PWM_PIN_6  8   // Channel 6
#define PWM_PIN_7  9   // Channel 7
#define PWM_PIN_8  10  // Channel 8

// Create PWM objects for each channel
ATmega_Slow_PWM ISR_PWM1, ISR_PWM2, ISR_PWM3, ISR_PWM4, ISR_PWM5, ISR_PWM6, ISR_PWM7, ISR_PWM8;

void setup() {
  // Initialize Serial Monitor for debugging
  Serial.begin(115200);
  while (!Serial);

  Serial.println("Starting 16 ISR-Based PWM Channels");

  // Initialize 8 PWM channels with their respective pins, frequencies, and duty cycles
  ISR_PWM1.setPWM(PWM_PIN_1, 1000, 50);    // Channel 1: 1kHz, 50% duty cycle
  ISR_PWM2.setPWM(PWM_PIN_2, 500, 25);     // Channel 2: 500Hz, 25% duty cycle
  ISR_PWM3.setPWM(PWM_PIN_3, 2000, 75);    // Channel 3: 2kHz, 75% duty cycle
  ISR_PWM4.setPWM(PWM_PIN_4, 1500, 10);    // Channel 4: 1.5kHz, 10% duty cycle
  ISR_PWM5.setPWM(PWM_PIN_5, 3000, 60);    // Channel 5: 3kHz, 60% duty cycle
  ISR_PWM6.setPWM(PWM_PIN_6, 2500, 40);    // Channel 6: 2.5kHz, 40% duty cycle
  ISR_PWM7.setPWM(PWM_PIN_7, 3500, 80);    // Channel 7: 3.5kHz, 80% duty cycle
  ISR_PWM8.setPWM(PWM_PIN_8, 4000, 20);    // Channel 8: 4kHz, 20% duty cycle

  // Continue setting up more channels if needed, up to 16 in total
}

void loop() {
  // The PWM signals are generated by the ISR, so the main loop can be free for other tasks.

  // Example: Change the duty cycle of Channel 1 every 5 seconds
  static unsigned long lastTime = 0;
  if (millis() - lastTime > 5000) {
    int newDutyCycle = random(10, 90); // Random duty cycle between 10% and 90%
    ISR_PWM1.setPWM(PWM_PIN_1, 1000, newDutyCycle);  // Update Channel 1 with new duty cycle

    Serial.print("Updated PWM1 Duty Cycle to: ");
    Serial.print(newDutyCycle);
    Serial.println("%");

    lastTime = millis(); // Reset the timer
  }

  delay(100);  // Short delay for Serial monitor output
}
